"""The comparison table: every detector, several datasets, mean and spread.

One dataset is an anecdote. This builds the same kind of dataset from several seeds, evaluates
every detector on each, and reports mean +- standard deviation, for three situations: a clean
training period, a training period with attacks hidden in it (what real logs are like), and a
stricter threshold.
"""

from __future__ import annotations

import statistics

from . import __version__
from .evaluate import DetectorResult, Evaluation, evaluate_spec
from .pipeline import TrainConfig
from .synth import ATTACK_TYPES, DatasetSpec

LABELS = {
    "zscore": "z-score (baseline)",
    "iforest": "Isolation Forest",
    "autoencoder": "Autoencoder",
    "sequence": "Next-event network",
    "vote": "Vote (2 of 3 learned)",
}


def _ms(values: list[float], digits: int = 2) -> str:
    spread = statistics.pstdev(values) if len(values) > 1 else 0.0
    return f"{statistics.fmean(values):.{digits}f} ± {spread:.{digits}f}"


def _runs(
    seeds: int, days: int, train_days: int, dirty: float, quantile: float
) -> list[Evaluation]:
    out = []
    for seed in range(1, seeds + 1):
        spec = DatasetSpec(days=days, train_days=train_days, seed=seed, dirty=dirty)
        out.append(evaluate_spec(spec, TrainConfig(seed=seed, quantile=quantile)))
    return out


def _quality_table(runs: list[Evaluation]) -> str:
    head = ("| Detector | ROC AUC | Avg precision | Precision | Recall | F1 | False alerts/day "
            "| Campaigns found |\n|---|---|---|---|---|---|---|---|")  # fmt: skip
    lines = [head]
    for name in LABELS:
        rows: list[DetectorResult] = [
            r.get(name) for r in runs if any(x.name == name for x in r.results)
        ]
        if not rows:
            continue
        found = [100 * r.campaigns_found / r.campaigns_total for r in rows]
        lines.append(
            f"| {LABELS[name]} | {_ms([r.auc for r in rows], 3)} | {_ms([r.ap for r in rows])} "
            f"| {_ms([r.precision for r in rows])} | {_ms([r.recall for r in rows])} "
            f"| {_ms([r.f1 for r in rows])} | {_ms([r.false_alerts_per_day for r in rows], 1)} "
            f"| {_ms(found, 0)} % |"
        )
    return "\n".join(lines)


def _type_table(runs: list[Evaluation]) -> str:
    names = [n for n in LABELS if any(x.name == n for x in runs[0].results)]
    lines = ["| Campaign type | " + " | ".join(LABELS[n] for n in names) + " |",
             "|---|" + "---|" * len(names)]  # fmt: skip
    for kind in ATTACK_TYPES:
        cells = []
        for name in names:
            done = sum(r.get(name).per_type.get(kind, (0, 0))[0] for r in runs)
            total = sum(r.get(name).per_type.get(kind, (0, 0))[1] for r in runs)
            cells.append(f"{100 * done / total:.0f} %" if total else "-")
        slow = " (low and slow)" if kind == "ssh_slow" else ""
        lines.append(f"| `{kind}`{slow} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _cost_table(runs: list[Evaluation]) -> str:
    lines = [
        "| Detector | Training (s) | Scoring one week (s) | Saved size (KB) |\n|---|---|---|---|"
    ]
    for name in LABELS:
        rows = [r.get(name) for r in runs if any(x.name == name for x in r.results)]
        if not rows or name == "vote":
            continue
        lines.append(f"| {LABELS[name]} | {_ms([r.train_seconds for r in rows], 1)} "
                     f"| {_ms([r.score_seconds for r in rows], 2)} "
                     f"| {_ms([r.model_kb for r in rows], 0)} |")  # fmt: skip
    return "\n".join(lines)


def run_benchmark(seeds: int = 5, days: int = 14, train_days: int = 7) -> str:
    """Run the whole comparison and return it as markdown."""
    clean = _runs(seeds, days, train_days, dirty=0.0, quantile=0.995)
    dirty = _runs(seeds, days, train_days, dirty=0.3, quantile=0.995)
    strict = _runs(seeds, days, train_days, dirty=0.0, quantile=0.999)
    first = clean[0]
    featurise = _ms([r.extra["featurise_seconds"] for r in clean], 2)
    return f"""# Results

Generated by `loganomaly benchmark --seeds {seeds}` (loganomaly {__version__}). Every number is the
mean ± standard deviation over {seeds} synthetic datasets of {days} days, each trained on the first
{train_days} days and tested on the rest. A test dataset has about {first.test_windows:,}
five-minute windows, {first.positive_windows} of them part of an attack, and
{first.events:,} log lines in total. See
[the evaluation method](models.md#how-the-comparison-is-made) for how windows are labelled
and what each column means.

**These are results on synthetic logs.** They show how the detectors behave relative to each
other. They do not predict your false-alert rate: run `loganomaly train` and `detect` on your own
logs for that.

## 1. Clean training period

Threshold at the 99.5th percentile of training scores.

{_quality_table(clean)}

## 2. Training period with attacks hidden in it

The same, but about 30 % of the test attacks are also present, unlabelled, in the training days.
Real logs are never clean, and a model that learns an attack as "normal" stops flagging it.

{_quality_table(dirty)}

## 3. A stricter threshold

Clean training, threshold at the 99.9th percentile: fewer false alerts, more missed attacks.

{_quality_table(strict)}

## 4. Which attacks each detector finds

Share of campaigns in which at least one window was flagged (clean training, threshold at the 99.5th
percentile).

{_type_table(clean)}

## 5. What each detector costs

{_cost_table(clean)}

Times are on one CPU core. Scoring is the detector alone; turning one week of events into
windows and features takes about {featurise} s on top,
once, whatever the detector. The vote is free once the detectors have run.
"""
